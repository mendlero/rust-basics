//! # Add n - adding consts and numbers with closures
//!
//! In this module we crate the simplest of addition functions with versions for the `Copy` and `Clone` traits and one with a Move (`FnOnce`)
//!
//! ## Examples
//! These may seem repetative. That's because they are :)
//! ### add_n
//! Adding a constant:
//! ```
//! use add_n::add_n;
//! let add_3 = add_n(3);
//!
//! assert_eq!(add_3(7), 10);
//! ```
//! Duration:
//! ```
//! use add_n::add_n;
//! use std::time::Duration;
//!
//! let five_secs = Duration::new(5, 0);
//! let ten_secs = Duration::new(10, 0);
//!
//! assert_eq!(add_n(five_secs)(ten_secs), Duration::new(15, 0));
//! // can still use the variable
//! println!("{:?}", five_secs);
//! ```
//!
//! ### add_n_clone
//! Adding a constant:
//! ```
//! use add_n::add_n_clone;
//! let add_3 = add_n_clone(3);
//!
//! assert_eq!(add_3(7), 10);
//! assert_eq!(add_3(6), 9);
//! ```
//! Duration:
//! ```
//! use add_n::add_n_clone;
//! use std::time::Duration;
//!
//! let five_secs = Duration::new(5, 0);
//! let ten_secs = Duration::new(10, 0);
//!
//! assert_eq!(add_n_clone(five_secs)(ten_secs), Duration::new(15, 0));
//! // can still use the variable
//! println!("{:?}", five_secs);
//! ```
//! ### add_n_once
//! Adding a constant:
//! ```
//! use add_n::add_n_once;
//! let add_3 = add_n_once(3);
//!
//! assert_eq!(add_3(7), 10);
//! // WILL fail compilation
//! // assert_eq!(add_3(6), 9);
//! ```
//! Duration:
//! ```
//! use add_n::add_n_once;
//! use std::time::Duration;
//!
//! let five_secs = Duration::new(5, 0);
//! let ten_secs = Duration::new(10, 0);
//!
//! assert_eq!(add_n_once(five_secs)(ten_secs), Duration::new(15, 0));
//! // can still use the variable... i guess
//! println!("{:?}", five_secs);
//! ```

use std::ops::Add;

pub fn add_n<T: Add<Output = T> + Copy>(n: T) -> impl Fn(T) -> T {
    move |x| n + x
}

pub fn add_n_clone<T: Add<Output = T> + Clone>(n: T) -> impl Fn(T) -> T {
    move |x| n.clone() + x
}

pub fn add_n_once<T: Add<Output = T>>(n: T) -> impl FnOnce(T) -> T {
    move |x| n + x
}

macro_rules! define_add_fns {
    ($($fn_name:ident: $t:ty),*) => {
        $(
            #[inline]
            pub fn $fn_name<const N: $t>(x: $t) -> $t {
                x + N
            }
        )*
    };
}

