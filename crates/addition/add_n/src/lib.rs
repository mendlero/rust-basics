    /// Range-based tests for a primitive `$t` whose operation adds the constant
    /// `$n`, overflowing above `$t::MAX - $n`.
    ///
    /// `[A-B]` is the no-overflow region `[MIN, MAX - N]`; `(B-)` is the
    /// overflowing region `[MAX - N + 1, MAX]`, probed at both boundaries and at
    /// an interior value. The region below `A` ("(-A)") is empty because `MIN` is
    /// already the type's floor.
    macro_rules! ranged_tests {
        ($module:ident, $t:ty, $n:literal, $expected:literal, $op:expr) => {
            mod $module {
                use super::super::*;

                const N: $t = $n;

                fn q1(lo: $t, hi: $t) -> $t {
                    (((lo as i128) * 3 + (hi as i128)) / 4) as $t
                }
                fn q3(lo: $t, hi: $t) -> $t {
                    (((lo as i128) + (hi as i128) * 3) / 4) as $t
                }

                // [A-B] = [MIN, MAX - N]: never overflows.
                #[test]
                fn no_overflow_region() {
                    let f = $op;
                    let safe_max = <$t>::MAX - N;
                    for x in [
                        <$t>::MIN,
                        q1(<$t>::MIN, safe_max),
                        q3(<$t>::MIN, safe_max),
                        safe_max,
                    ] {
                        assert_eq!(f(x), x + N, "no-overflow region, x = {x}");
                    }
                }

                // (B-) = [MAX - N + 1, MAX]: always overflows.
                #[cfg(debug_assertions)]
                #[test]
                #[should_panic(expected = $expected)]
                fn overflow_lower_boundary() {
                    let f = $op;
                    let _ = f(<$t>::MAX - N + 1);
                }

                #[cfg(debug_assertions)]
                #[test]
                #[should_panic(expected = $expected)]
                fn overflow_inner() {
                    let f = $op;
                    let lo = <$t>::MAX - N + 1;
                    let _ = f(q1(lo, <$t>::MAX));
                }

                #[cfg(debug_assertions)]
                #[test]
                #[should_panic(expected = $expected)]
                fn overflow_upper_boundary() {
                    let f = $op;
                    let _ = f(<$t>::MAX);
                }
            }
        };
    }

    /// Range-based tests for `MyInt`, which overflows at the same point as
    /// `i32` but cannot go through `ranged_tests!` (that macro casts integers).
    macro_rules! myint_ranged_tests {
        ($module:ident, $op:expr) => {
            mod $module {
                use super::super::*;
                use super::MyInt;

                const N: i32 = 7;
                const SAFE_MAX: i32 = i32::MAX - N;

                #[test]
                fn no_overflow_region() {
                    let f = $op;
                    for v in [i32::MIN, 0, 1_000_000, SAFE_MAX] {
                        assert_eq!(f(MyInt(v)), MyInt(v + N), "no-overflow region, x = {v}");
                    }
                }

                #[test]
                #[should_panic(expected = "MyInt addition overflowed")]
                fn overflow_lower_boundary() {
                    let f = $op;
                    let _ = f(MyInt(SAFE_MAX + 1));
                }

                #[test]
                #[should_panic(expected = "MyInt addition overflowed")]
                fn overflow_inner() {
                    let f = $op;
                    let _ = f(MyInt(i32::MAX - 3));
                }

                #[test]
                #[should_panic(expected = "MyInt addition overflowed")]
                fn overflow_upper_boundary() {
                    let f = $op;
                    let _ = f(MyInt(i32::MAX));
                }
            }
        };
    }

